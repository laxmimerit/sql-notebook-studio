/** The package folder that a bundled input path belongs to, or undefined. */
function packageDir(input) {
  const parts = input.replace(/\\/g, '/').split('/');
  const i = parts.lastIndexOf('node_modules');
  if (i < 0) return undefined;
  const len = parts[i + 1]?.startsWith('@') ? 2 : 1;
  return parts.slice(0, i + 1 + len).join('/');
}

function licenseTexts(dir) {
  return readdirSync(dir)
    .filter((f) => /^(licen[cs]e|copying)([-._].*)?$/i.test(f))
    .sort()
    .map((f) => readFileSync(join(dir, f), 'utf8').trim());
}

/** @param {import('esbuild').Metafile[]} metafiles */
export function writeNotices(metafiles, file = 'THIRD-PARTY-NOTICES.txt') {
  const dirs = new Set(COPIED.map((name) => `node_modules/${name}`));
  for (const meta of metafiles) {
    for (const input of Object.keys(meta.inputs)) {
      const dir = packageDir(input);
      if (dir) dirs.add(dir);
    }
  }

  const byName = new Map();
  for (const dir of dirs) {
    if (!existsSync(join(dir, 'package.json'))) continue;
    const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    if (pkg.name === 'sql-notebook-studio') continue;
    const license =
      typeof pkg.license === 'string'
        ? pkg.license
        : pkg.license?.type ?? (pkg.licenses?.map((l) => l.type ?? l).join(' OR ') || 'see package');
    const key = `${pkg.name}@${pkg.version}`;
    if (!byName.has(key)) byName.set(key, { key, license, texts: licenseTexts(dir) });
  }

  const sections = [...byName.values()]
    .sort((a, b) => a.key.localeCompare(b.key))
    .map(({ key, license, texts }) =>
      [`${key}`, `License: ${license}`, '', texts.length ? texts.join('\n\n') : `(No license file in the package. Its package.json says ${license}.)`].join('\n'),
    );

  const rule = '\n\n' + '-'.repeat(78) + '\n\n';
  const header =
    'SQL Notebook Studio includes the third-party software below.\n' +
    'Each part is under its own license, shown with it.\n' +
    'This file is generated by scripts/build.mjs. Do not edit it by hand.';
  writeFileSync(file, [header, MICROSOFT, ...sections].join(rule) + '\n');
  return byName.size + 1;
}
